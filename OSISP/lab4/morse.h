#ifndef MORSE_H
#define MORSE_H

#include <stddef.h>

/* Максимальная длина кода Морзе для одного символа (включая '\0') */
#define MORSE_CODE_MAX 8

/*
 * Кодирует символ c в строку Морзе (точки и тире). Записывает в buf, не более buf_size байт.
 * Возвращает длину записи или 0, если символ не преобразуется (непреобразуемые отбрасываются).
 */
size_t morse_encode_char(char c, char *buf, size_t buf_size);

/*
 * Декодирует строку Морзе (только точки, тире, пробелы) в один символ.
 * Возвращает символ или '\0' при нераспознанной комбинации.
 */
char morse_decode(const char *morse);

#endif
